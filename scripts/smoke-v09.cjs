const { _electron: electron, expect } = require('@playwright/test');
const path = require('node:path');
const fs = require('node:fs/promises');
(async () => {
  const root = path.resolve(__dirname, '..');
  const data = await fs.mkdtemp(path.join(require('node:os').tmpdir(), 'fusion-v09-'));
  const output = path.join(root, 'test-output/v0.9');
  await fs.mkdir(output, { recursive: true });
  await fs.writeFile(path.join(data, 'settings.json'), JSON.stringify({ selectedVersion: '1.20.1', discordPresence: false, autoCheckUpdates: false }));
  const env = { ...process.env, FUSION_TEST_DATA: data }; delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ executablePath: require('electron'), args: [path.join(root, 'scripts/headless-entry.cjs')], env });
  try {
    const page = await app.firstWindow(); const errors = [];
    page.setDefaultTimeout(20000);
    async function screenshot({ path: file }) { await page.waitForTimeout(350); const data = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG().toString('base64')); await fs.writeFile(file, Buffer.from(data, 'base64')); }
    page.on('pageerror', error => errors.push(error.message));
    expect(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible())).toBe(false);
    await expect(page.getByRole('button', { name: /^Launch 1.20.1/ })).toBeEnabled({ timeout: 45000 });
    await expect.poll(() => page.locator('.hero-art').evaluate(img => img.naturalWidth)).toBeGreaterThan(0);
    await expect(page.locator('.compact-news .news-card').first()).toBeVisible({ timeout: 30000 });
    await screenshot({ path: path.join(output, 'play.png') });
    await page.getByRole('button', { name: 'Choose Minecraft version' }).click();
    await page.getByRole('textbox', { name: 'Find a version' }).fill('1.12.1');
    await expect(page.locator('.picker-options button')).toHaveCount(1);
    await screenshot({ path: path.join(output, 'version-picker.png') });
    await page.locator('.picker-options button').click();
    await expect(page.getByRole('button', { name: /^Launch 1.12.1/ })).toBeVisible();
    await page.getByRole('button', { name: 'Use 1.20.1', exact: true }).click();
    await expect(page.getByRole('button', { name: /^Launch 1.20.1/ })).toBeVisible();
    await app.evaluate(({ shell }) => { shell.openExternal = async url => { global.__openedAuthUrl = url; }; });
    await page.getByRole('button', { name: /^Launch 1.20.1/ }).click();
    await expect(page.getByRole('button', { name: 'Waiting for Microsoft…' })).toBeVisible();
    const authURL = await app.evaluate(() => global.__openedAuthUrl);
    expect(new URL(new URL(authURL).searchParams.get('redirect_uri')).hostname).toBe('localhost');
    await page.getByRole('button', { name: 'Close dialog' }).click();
    expect((await page.evaluate(() => window.fusion.launch('1.20.1'))).ok).toBe(false);
    await page.getByRole('button', { name: 'Mods', exact: true }).click();
    await expect(page.locator('.mod-result:not(.skeleton)').first()).toBeVisible({ timeout: 30000 });
    await page.getByRole('textbox', { name: 'Search Modrinth' }).fill('sodium extra');
    await expect(page.getByRole('button', { name: 'Install Sodium Extra', exact: true })).toBeVisible({ timeout: 30000 });
    await screenshot({ path: path.join(output, 'mods.png') });
    await page.getByRole('button', { name: 'Install Sodium Extra', exact: true }).click();
    await expect(page.getByRole('dialog', { name: 'Install mods' })).toBeVisible({ timeout: 30000 });
    await expect(page.locator('.dependency-list')).toContainText('Fabric API');
    await screenshot({ path: path.join(output, 'dependencies.png') });
    await page.getByRole('button', { name: 'Install & use Fabric' }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0, { timeout: 60000 });
    await expect(page.getByRole('button', { name: 'Active profile' })).toBeVisible();
    await page.getByRole('tab', { name: /Installed/ }).click();
    await expect(page.locator('.installed-list article')).toHaveCount(3);
    await screenshot({ path: path.join(output, 'installed.png') });
    await page.getByRole('button', { name: 'Remove Fabric API', exact: true }).click();
    await expect(page.getByRole('alert')).toContainText('Required by');
    await page.getByRole('tab', { name: 'Built-in Fusion' }).click();
    await expect(page.getByLabel('Enable Fusion Focus')).toBeVisible();
    await page.getByRole('button', { name: 'News', exact: true }).click();
    await expect(page.locator('.news-card')).toHaveCount(18);
    await screenshot({ path: path.join(output, 'news.png') });
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await expect(page.getByLabel('Launch profile')).toHaveValue('fabric');
    await screenshot({ path: path.join(output, 'settings.png') });
    await page.getByLabel('Accent color').selectOption('blue');
    await page.getByLabel('Reduce motion').check();
    await page.getByRole('button', { name: 'Save changes' }).click();
    await expect(page.locator('.app-shell')).toHaveAttribute('data-accent', 'blue');
    await page.getByRole('button', { name: 'Play', exact: true }).click();
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(980, 660));
    await screenshot({ path: path.join(output, 'play-small-blue.png') });
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
    expect(errors).toEqual([]);
    console.log('PASS: hidden Electron window; quick selection; direct browser login/cancel; real Modrinth search, dependencies, download, inventory, guarded removal; news; settings; compact blue layout.');
    console.log(output);
  } finally { await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
